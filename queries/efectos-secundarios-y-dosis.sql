## Resumen de Dosis y Efectos de Fármacos Veterinarios

### Propofol
- **Uso**: Inducción anestésica en animales.
- **Dosis**: 6.0–8.0 mg/kg, ajustado según alertas clínico.
- **Efectos secundarios**: Hipotensión, apnea.

### Ketamina
- **Uso**: Inducción rápida y analgésico.
- **Dosis**: 5–10 mg/kg.
- **Efectos secundarios**: Hiperactividad y disociación en dosis altas. Se recomienda el uso combinado con xilazina.

### Xilazina
- **Uso**: Sedante y analgésico.
- **Dosis en rumiantes**: 0.05 mg/kg.
- **Dosis en equinos**: 0.2 mg/kg.
- **Efectos secundarios**: Bradicardia y depresión respiratoria en dosis excesivas.

### Norepinefrina
- **Uso**: Manejo de shock distributivo.
- **Dosis**: 0.05–2 mcg/kg/min en infusión continua.
- **Efectos secundarios**: Vasoconstricción excesiva, bradicardia, metabilismo variable en diferentes especies.

### Epinefrina
- **Uso**: Emergencias, anafilaxia.
- **Dosis**: 0.01–0.02 mg/kg SC o IV.
- **Efectos secundarios**: Arritmias, aumento de la presión arterial.

### Hemodrag (Etamsilato)
- **Dosis**: 5–12.5 mg/kg. Indicaciones en hemorragias.

### Atropina
- **Uso**: Manejo de bradicardia.
- **Dosis**: 0.02-0.04 mg/kg IM.
- **Efectos secundarios**: Xerostomía, taquicardia.

### Consideraciones Generales
- **Dosis adecuadas**: Es vital ajustarlas según el peso y la especie.
- **Interacciones**: Es importante revisar las interacciones farmacológicas, especialmente en polifarmacia.
- **Monitoreo**: Los efectos adversos deben ser monitoreados continuamente durante la anestesia.
