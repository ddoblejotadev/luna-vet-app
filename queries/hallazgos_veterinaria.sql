# Hallazgos de investigación y dosis de medicamentos veterinarios

## Mastilac
- **Presentaciones**:
  - Inyectable con Lincomicina y Neomicina (200 mg + 500 mg respectivamente)
  - Inyección de Amoxicilina (140 mg + 35 mg clavulánico)
- **Dosiación**: 8.75 mg/kg q24h

## Tiopental
- **Dosis**: Inducción estándar 5-15 mg/kg según el protocolo

## Epinefrina (Adrenalina)
- **Dosis**: 0.01–0.02 mg/kg, riesgo crítico

## Norepinefrina (Noradrenalina)
- **Dosis**: 0.05 a 2 microgramos/kg/min en infusión continua
- **Indicaciones**: Shock distributivo y anestésicos
- **Consideraciones**: Evitar en pacientes con arritmias previas

## Hemodrag (Etamsilato)
- **Indicaciones**: Manejo de hemorragia y estabilización de la hemostasia
- **Dosis recomendadas**: 5–12.5 mg/kg IV/IM

## Dopamina y Dobutamina
- **Dopamina**: Dosis: 1–5 microgramos/kg/min
- **Dobutamina**: Dosis: 2-10 microgramos/kg/min

## Atropina
- **Presentaciones**: 0.5 mg/mL inyectable
- **Usos**: Manejo de bradicardia y como antídoto

## Observaciones Adicionales
- Verificar eficiencia en administración y consideraciones específicas según la especie.
